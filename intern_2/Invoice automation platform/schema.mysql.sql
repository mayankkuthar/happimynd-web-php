-- Conventions (same as on Postgres today):
--   * Timestamps are UTC, DATETIME(3). Prisma writes UTC; run the server with time_zone UTC.
--   * IDs are cuid strings generated by Prisma Client, not by the database.
--   * Prisma's Postgres `TEXT` columns become VARCHAR(191) here unless schema.prisma marks them
--     @db.Text / @db.MediumText / @db.LongText. Free-text columns are marked; keys stay VARCHAR so
--     they can be indexed.
--   * Collation utf8mb4_unicode_ci: comparisons and unique keys ignore case, accents and trailing
--     spaces. This replaces the Postgres `mode: "insensitive"` searches.
--   * The two Postgres text[] columns (InvoiceTransaction.flags, Template.dependencyFields) are
--     JSON arrays here, holding the same values.

