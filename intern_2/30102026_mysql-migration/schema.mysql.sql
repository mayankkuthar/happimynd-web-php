-- HR Auto (Resume Extractor): MySQL schema
-- Target: MySQL 8.0.19+ / 8.4, or Aurora MySQL 3 (InnoDB, utf8mb4).
-- Tested on MySQL 8.4.7 with time_zone '+00:00' (MIGRATION_GUIDE.md, top).
--
-- The end state of server/src/db/migrations/001-005, in one file, for loading
-- an empty database by hand. The API does the same thing itself on first boot
-- (DATABASE_AUTO_MIGRATE=1), so this file is optional; MIGRATION_GUIDE.md §4.2.
--
-- Safe to run more than once: every statement is CREATE ... IF NOT EXISTS,
-- CREATE OR REPLACE or INSERT IGNORE. The last statement records 001-005 in
-- schema_migrations, so the API does not re-apply them on top of this file.
--
-- Conventions (same as the current app):
--   * All timestamps are UTC. Run the server/session with time_zone = '+00:00'.
--   * IDs are generated by the API: 12 lowercase hex characters for records,
--     "APP-" + 10 characters for applications.
--   * fields / confidence / log are JSON documents, read and written whole by
--     the application.
--   * Resume text, names and file names contain non-ASCII text and emoji, so
--     everything is utf8mb4.

SET NAMES utf8mb4;
SET time_zone = '+00:00';

-- ─────────────────────────────────────────────────────────────────────
-- records: one row per uploaded resume.
--
-- This table is also the work queue. The API claims the oldest 'queued' row
-- with SELECT ... FOR UPDATE SKIP LOCKED, so any number of API instances can
-- share a batch without handing one file to two workers (see
-- MIGRATION_GUIDE.md §5.1 for the claim).
-- ─────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS records (
  -- IDs and checksums are ASCII and compared exactly, not case-insensitively.
  id            VARCHAR(64)  CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  file_name     VARCHAR(512) NOT NULL,                  -- display name, sanitised by the API (≤ 255 chars today)
  size_bytes    BIGINT       NOT NULL,
  checksum      CHAR(64)     CHARACTER SET ascii COLLATE ascii_bin NOT NULL,  -- SHA-256 hex of the file bytes
  source        VARCHAR(20)  NOT NULL,                  -- 'linkedin' | 'indeed' | 'naukri' | 'email' | 'others'
  department    VARCHAR(40)      NULL,                  -- NULL only for rows uploaded before departments existed
  status        VARCHAR(12)  NOT NULL DEFAULT 'queued', -- 'queued' | 'processing' | 'done' | 'error'
  viewed        TINYINT(1)   NOT NULL DEFAULT 0,        -- was BOOLEAN
  -- Object-storage key for the original file. NULL once the file is gone;
  -- the UI disables preview on that.
  storage_key   VARCHAR(512)     NULL,
  content_type  VARCHAR(255) NOT NULL DEFAULT 'application/pdf',  -- sniffed at upload; served back on preview
  fields        JSON         NOT NULL DEFAULT (JSON_OBJECT()),    -- all 56 extracted fields
  confidence    JSON         NOT NULL DEFAULT (JSON_OBJECT()),    -- per field: 'high' | 'medium' | 'low' | 'none'
  text_content  MEDIUMTEXT   NOT NULL DEFAULT (''),               -- full extracted text; can exceed TEXT's 64 KB
  log           JSON         NOT NULL DEFAULT (JSON_ARRAY()),     -- per-file processing narrative (array of strings)
  error         TEXT             NULL,
  used_ocr      TINYINT(1)   NOT NULL DEFAULT 0,
  page_count    INT          NOT NULL DEFAULT 0,
  ai_status     VARCHAR(12)  NOT NULL DEFAULT 'disabled',  -- 'ok' | 'failed' | 'disabled' | 'skipped'
  -- Duplicates are flagged, not rejected, so the recruiter can decide.
  duplicate_of  VARCHAR(64)  CHARACTER SET ascii COLLATE ascii_bin NULL,
  attempts      INT          NOT NULL DEFAULT 0,
  claimed_at    DATETIME(3)      NULL,                  -- UTC; set while a worker holds the row
  created_at    DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),  -- UTC; reset by reprocess
  finished_at   DATETIME(3)      NULL,                  -- UTC

  -- ── Read-only candidate columns (were migrations 004 and 006) ──────
  -- STORED generated columns computed from `fields` on every insert and
  -- update, so they cannot drift and the application never writes them. An
  -- UPDATE that targets one is rejected; corrections go through
  -- PATCH /api/resumes/:id, which writes `fields`, and the column follows.
  --
  -- Each expression returns NULL for a missing key, a JSON null, or an empty
  -- string, matching Postgres's NULLIF(fields ->> 'x', ''). The JSON_TYPE test
  -- is needed because MySQL's JSON_UNQUOTE turns a JSON null into the text
  -- 'null'. Indexed columns are cut with LEFT() so an oversized model answer
  -- can never make an INSERT/UPDATE fail on length.
  --
  -- The three list fields (technical_skills, project_names,
  -- certification_names) are not here: MySQL does not allow subqueries or
  -- stored functions in generated columns, so they live in the
  -- `records_candidates` view below instead.

  -- Basic information
  candidate_name VARCHAR(255) GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.candidate_name')) = 'NULL', NULL, LEFT(NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.candidate_name')), ''), 255))) STORED,
  email          VARCHAR(320) GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.email')) = 'NULL', NULL, LEFT(NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.email')), ''), 320))) STORED,
  phone          MEDIUMTEXT GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.phone')) = 'NULL', NULL, NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.phone')), ''))) STORED,
  alternate_phone MEDIUMTEXT GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.alternate_phone')) = 'NULL', NULL, NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.alternate_phone')), ''))) STORED,

  -- Experience
  current_job_title      MEDIUMTEXT GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.current_job_title')) = 'NULL', NULL, NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.current_job_title')), ''))) STORED,
  current_company        MEDIUMTEXT GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.current_company')) = 'NULL', NULL, NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.current_company')), ''))) STORED,
  current_designation    MEDIUMTEXT GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.current_designation')) = 'NULL', NULL, NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.current_designation')), ''))) STORED,
  total_experience_years MEDIUMTEXT GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.total_experience_years')) = 'NULL', NULL, NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.total_experience_years')), ''))) STORED,
  -- One role per line, "Title | Company | Dates".
  employment_history     MEDIUMTEXT GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.employment_history')) = 'NULL', NULL, NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.employment_history')), ''))) STORED,

  -- Location
  location MEDIUMTEXT GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.location')) = 'NULL', NULL, NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.location')), ''))) STORED,
  city     MEDIUMTEXT GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.city')) = 'NULL', NULL, NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.city')), ''))) STORED,
  state    MEDIUMTEXT GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.state')) = 'NULL', NULL, NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.state')), ''))) STORED,
  country  MEDIUMTEXT GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.country')) = 'NULL', NULL, NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.country')), ''))) STORED,

  -- Links
  linkedin  MEDIUMTEXT GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.linkedin')) = 'NULL', NULL, NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.linkedin')), ''))) STORED,
  github    MEDIUMTEXT GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.github')) = 'NULL', NULL, NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.github')), ''))) STORED,
  portfolio MEDIUMTEXT GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.portfolio')) = 'NULL', NULL, NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.portfolio')), ''))) STORED,

  -- Education
  highest_qualification MEDIUMTEXT GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.highest_qualification')) = 'NULL', NULL, NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.highest_qualification')), ''))) STORED,
  degree                MEDIUMTEXT GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.degree')) = 'NULL', NULL, NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.degree')), ''))) STORED,
  specialization        MEDIUMTEXT GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.specialization')) = 'NULL', NULL, NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.specialization')), ''))) STORED,
  university            MEDIUMTEXT GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.university')) = 'NULL', NULL, NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.university')), ''))) STORED,
  graduation_year       MEDIUMTEXT GENERATED ALWAYS AS (IF(JSON_TYPE(JSON_EXTRACT(fields, '$.graduation_year')) = 'NULL', NULL, NULLIF(JSON_UNQUOTE(JSON_EXTRACT(fields, '$.graduation_year')), ''))) STORED,

  PRIMARY KEY (id),

  -- Listing a source's records in upload order (GET /api/resumes?source=).
  KEY idx_records_source_created (source, created_at),
  -- Duplicate detection is scoped to the source.
  KEY idx_records_source_checksum (source, checksum),
  -- Queue claim (status = 'queued' ORDER BY created_at) and status counts.
  -- MySQL has no partial indexes; this replaces records_queue_idx.
  KEY idx_records_status_created (status, created_at),
  -- The reaper that requeues rows orphaned by a crashed instance.
  -- Replaces records_claimed_idx.
  KEY idx_records_status_claimed (status, claimed_at),
  KEY idx_records_department (department, created_at),
  -- "Rows where AI extraction did not run" (ai_status <> 'ok').
  KEY idx_records_ai_status (ai_status, created_at),
  -- utf8mb4_0900_ai_ci is case-insensitive, so these replace the Postgres
  -- lower(email) / lower(candidate_name) indexes.
  KEY idx_records_email (email),
  KEY idx_records_candidate_name (candidate_name),
  KEY idx_records_duplicate_of (duplicate_of),

  CONSTRAINT fk_records_duplicate_of
    FOREIGN KEY (duplicate_of) REFERENCES records (id) ON DELETE SET NULL,
  -- CHECK constraints are enforced from MySQL 8.0.16.
  CONSTRAINT chk_records_status
    CHECK (status IN ('queued', 'processing', 'done', 'error'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- ─────────────────────────────────────────────────────────────────────
-- records_candidates: a readable, one-row-per-resume view for table browsers
-- and ad-hoc SQL. The app never reads it.
--
-- It adds the three list fields the generated columns above cannot express,
-- joined with '; ' the way the results table and the Excel export join them.
-- GROUP_CONCAT stops at group_concat_max_len (1024 bytes by default); set it
-- to 1048576 in the parameter group (MIGRATION_GUIDE.md §8.1) or long skill
-- lists come back cut short.
-- ─────────────────────────────────────────────────────────────────────
CREATE OR REPLACE VIEW records_candidates AS
SELECT
  r.id,
  r.source,
  r.department,
  r.status,
  r.ai_status,
  r.viewed,
  r.file_name,
  r.candidate_name,
  r.email,
  r.phone,
  r.alternate_phone,
  r.current_job_title,
  r.current_company,
  r.current_designation,
  r.total_experience_years,
  r.employment_history,
  r.location,
  r.city,
  r.state,
  r.country,
  r.linkedin,
  r.github,
  r.portfolio,
  r.highest_qualification,
  r.degree,
  r.specialization,
  r.university,
  r.graduation_year,
  -- The three list fields follow Postgres jsonb_text_list(): an array is
  -- joined, a JSON null or missing key is NULL, and any other value (a model
  -- that answered with a string) is shown as its text.
  CASE JSON_TYPE(JSON_EXTRACT(r.fields, '$.technical_skills'))
    WHEN 'ARRAY' THEN
      (SELECT NULLIF(GROUP_CONCAT(jt.item ORDER BY jt.ord SEPARATOR '; '), '')
         FROM JSON_TABLE(r.fields, '$.technical_skills[*]'
                COLUMNS (ord FOR ORDINALITY, item VARCHAR(2000) PATH '$')) AS jt)
    WHEN 'NULL' THEN NULL
    ELSE NULLIF(JSON_UNQUOTE(JSON_EXTRACT(r.fields, '$.technical_skills')), '')
  END AS technical_skills,
  CASE JSON_TYPE(JSON_EXTRACT(r.fields, '$.project_names'))
    WHEN 'ARRAY' THEN
      (SELECT NULLIF(GROUP_CONCAT(jt.item ORDER BY jt.ord SEPARATOR '; '), '')
         FROM JSON_TABLE(r.fields, '$.project_names[*]'
                COLUMNS (ord FOR ORDINALITY, item VARCHAR(2000) PATH '$')) AS jt)
    WHEN 'NULL' THEN NULL
    ELSE NULLIF(JSON_UNQUOTE(JSON_EXTRACT(r.fields, '$.project_names')), '')
  END AS project_names,
  CASE JSON_TYPE(JSON_EXTRACT(r.fields, '$.certification_names'))
    WHEN 'ARRAY' THEN
      (SELECT NULLIF(GROUP_CONCAT(jt.item ORDER BY jt.ord SEPARATOR '; '), '')
         FROM JSON_TABLE(r.fields, '$.certification_names[*]'
                COLUMNS (ord FOR ORDINALITY, item VARCHAR(2000) PATH '$')) AS jt)
    WHEN 'NULL' THEN NULL
    ELSE NULLIF(JSON_UNQUOTE(JSON_EXTRACT(r.fields, '$.certification_names')), '')
  END AS certification_names,
  r.created_at,
  r.finished_at
FROM records AS r;

-- ─────────────────────────────────────────────────────────────────────
-- schema_migrations: the API's migration ledger (server/src/db/migrate.ts).
-- Created here so the runner finds it; see MIGRATION_GUIDE.md §5.3 for how
-- it is used.
-- ─────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS schema_migrations (
  name       VARCHAR(255) NOT NULL,
  applied_at DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- ─────────────────────────────────────────────────────────────────────
-- applications, application_notes, application_emails, audit_log: the
-- candidate portal (/apply) and the hiring dashboard. Separate from records:
-- applications are what a candidate typed; records are what the extractor read.
-- ─────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS applications (
  -- "APP-" + 10 characters, generated by the API and shown to the candidate.
  id                  VARCHAR(32)  CHARACTER SET ascii COLLATE ascii_bin NOT NULL,

  -- Personal
  full_name           VARCHAR(200) NOT NULL,
  email               VARCHAR(320) NOT NULL,
  phone               VARCHAR(32)  NOT NULL,                -- as typed, trimmed
  phone_digits        VARCHAR(20)  CHARACTER SET ascii NOT NULL,  -- last 10 digits, for duplicate matching

  -- Education
  college             VARCHAR(255) NOT NULL,
  degree              VARCHAR(255) NOT NULL,
  specialization      VARCHAR(255)     NULL,
  graduation_year     SMALLINT         NULL,
  education_details   TEXT             NULL,

  -- Professional
  current_position    VARCHAR(255)     NULL,                -- "Current role / status"
  experience_years    DECIMAL(4,1) NOT NULL DEFAULT 0,
  previous_experience TEXT             NULL,
  skills              JSON         NOT NULL DEFAULT (JSON_ARRAY()),

  -- Application
  applied_role        VARCHAR(255) NOT NULL,
  preferred_location  VARCHAR(255)     NULL,
  notice_period       VARCHAR(100)     NULL,

  -- Links
  linkedin_url        VARCHAR(500)     NULL,
  github_url          VARCHAR(500)     NULL,
  portfolio_url       VARCHAR(500)     NULL,
  other_links         TEXT             NULL,

  -- Resume. The key is server-generated from the id; the name is display only.
  resume_storage_key  VARCHAR(512)     NULL,
  resume_file_name    VARCHAR(255)     NULL,
  resume_content_type VARCHAR(255)     NULL,
  resume_size_bytes   BIGINT           NULL,

  -- Workflow. No CHECK on status: the stage list is configuration
  -- (APPLICATION_STATUSES) and the API validates against it.
  status              VARCHAR(40)  NOT NULL DEFAULT 'New',
  -- An earlier application from the same person for a different role.
  duplicate_of        VARCHAR(32)  CHARACTER SET ascii COLLATE ascii_bin NULL,
  -- The `records` row created for this resume (no FK: written before the record exists).
  record_id           VARCHAR(64)  CHARACTER SET ascii COLLATE ascii_bin NULL,

  created_at          DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at          DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  status_changed_at   DATETIME(3)      NULL,
  last_contacted_at   DATETIME(3)      NULL,

  PRIMARY KEY (id),
  KEY idx_applications_created (created_at),
  KEY idx_applications_status_created (status, created_at),
  KEY idx_applications_role (applied_role, created_at),
  KEY idx_applications_email (email),
  KEY idx_applications_phone_digits (phone_digits),
  KEY idx_applications_name (full_name),
  KEY idx_applications_duplicate_of (duplicate_of),
  KEY idx_applications_record (record_id),

  CONSTRAINT fk_applications_duplicate_of
    FOREIGN KEY (duplicate_of) REFERENCES applications (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- Internal hiring notes. Never exposed to the candidate.
CREATE TABLE IF NOT EXISTS application_notes (
  id             BIGINT       NOT NULL AUTO_INCREMENT,
  application_id VARCHAR(32)  CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  author         VARCHAR(100) NOT NULL,
  body           TEXT         NOT NULL,
  created_at     DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_application_notes_app (application_id, created_at),
  CONSTRAINT fk_application_notes_app
    FOREIGN KEY (application_id) REFERENCES applications (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- Every email sent to a candidate, successful or not.
CREATE TABLE IF NOT EXISTS application_emails (
  id             BIGINT       NOT NULL AUTO_INCREMENT,
  application_id VARCHAR(32)  CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  recipient      VARCHAR(320) NOT NULL,
  subject        VARCHAR(255) NOT NULL,
  body           MEDIUMTEXT   NOT NULL,
  sent_by        VARCHAR(100) NOT NULL,            -- admin username, or 'system' for the acknowledgement
  status         VARCHAR(12)  NOT NULL,            -- 'sent' | 'failed'
  error          TEXT             NULL,
  message_id     VARCHAR(255)     NULL,            -- SMTP Message-ID, for tracing with the mail provider
  created_at     DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_application_emails_app (application_id, created_at),
  CONSTRAINT fk_application_emails_app
    FOREIGN KEY (application_id) REFERENCES applications (id) ON DELETE CASCADE,
  CONSTRAINT chk_application_emails_status CHECK (status IN ('sent', 'failed'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- Admin actions. No foreign key: the trail has to outlive what it describes.
CREATE TABLE IF NOT EXISTS audit_log (
  id          BIGINT       NOT NULL AUTO_INCREMENT,
  actor       VARCHAR(100) NOT NULL,
  action      VARCHAR(60)  NOT NULL,              -- 'application.status', 'application.email', ...
  entity_type VARCHAR(40)  NOT NULL,
  entity_id   VARCHAR(64)  NOT NULL,
  detail      JSON             NULL,
  created_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_audit_entity (entity_type, entity_id, created_at),
  KEY idx_audit_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- ─────────────────────────────────────────────────────────────────────
-- departments: the list behind the upload prompt's department picker. The
-- admin can add to it; records.department stores the name itself (no FK).
-- ─────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS departments (
  -- Same width as records.department. The collation is case-insensitive, so
  -- the primary key also stops "it" being added alongside "IT".
  name       VARCHAR(40) NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

